"""Краткая справка по маркировке. Не реестр и не юридическое заключение."""

from __future__ import annotations

from typing import Any

SOURCE = "справочник требований маркировки"

_TOPICS: dict[str, str] = {
    "erid": (
        "erid — уникальный идентификатор интернет-рекламы, присваивается при "
        "регистрации креатива через аккредитованного ОРД и передаётся в ЕРИР."
    ),
    "ord": (
        "ОРД (оператор рекламных данных) — посредник между рекламодателем и ЕРИР: "
        "регистрирует креативы, присваивает erid, передаёт статистику."
    ),
    "erir": (
        "ЕРИР — единый реестр интернет-рекламы. Полный доступ к базе закрыт "
        "(ведомства и операторы). Этот продукт в ЕРИР сам по себе не ходит."
    ),
    "responsibility": (
        "Ответственность за корректную маркировку по 38-ФЗ несёт рекламодатель и "
        "рекламораспространитель, не данный сервис-валидатор."
    ),
    "deadlines": (
        "Маркировка и передача данных в ЕРИР — до размещения рекламы; "
        "отчётность по показам — по правилам конкретного ОРД."
    ),
    "fines": (
        "Штрафы по ст. 14.3 КоАП за нарушения маркировки — на рекламодателя/"
        "распространителя; размер зависит от состава (справочно, не юр-заключение)."
    ),
}


def explain_topic(topic: str) -> dict[str, Any]:
    key_raw = topic.strip().lower()
    key = key_raw.split()[0] if key_raw else ""
    body = _TOPICS.get(key) or _TOPICS.get(key_raw)
    if not body:
        body = (
            f"Тема «{topic}» не найдена. Доступные ключи: "
            + ", ".join(sorted(_TOPICS))
        )
    return {
        "ready": True,
        "topic": key_raw,
        "summary_ru": body,
        "source": SOURCE,
    }
